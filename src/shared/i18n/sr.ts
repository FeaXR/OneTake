/** Serbian has three plural forms: 1, 21 (one); 2-4, 22 (few); 0, 5-20, 25 (many). */
const plural = (count: string | number, one: string, few: string, many: string) => {
  const n = Math.abs(Number(count));
  const last = n % 10;
  const lastTwo = n % 100;
  if (last === 1 && lastTwo !== 11) return one;
  return last >= 2 && last <= 4 && (lastTwo < 12 || lastTwo > 14) ? few : many;
};
const files = (n: string | number) => plural(n, 'датотека', 'датотеке', 'датотека');

