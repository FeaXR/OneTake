// Writes the package-manager files for a release: the AUR package (PKGBUILD and .SRCINFO), the
// Scoop manifest and the winget manifests. The release workflow runs it after publishing a
// release, with the built files at hand:
//
//   node scripts/package-manifests.mjs <version> <folder with the release files> <output folder>
//
// It writes <output>/aur/ when the .deb is there, and <output>/winget/ and
// <output>/scoop/one-take.json when the Windows installer is. Copies that a
// package manager installs carry a "package-manager" file in their resources folder, so the app
// leaves updating to that package manager (see src/main/updates.ts).
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [version, releaseDir, outDir] = process.argv.slice(2);
if (!/^\d+\.\d+\.\d+$/.test(version ?? '') || !releaseDir || !outDir) {
  console.error('Usage: node scripts/package-manifests.mjs <version> <release folder> <output folder>');
  process.exit(1);
}

const root = join(import.meta.dirname, '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const { owner, repo } = pkg.build.publish[0];
const homepage = `https://github.com/${owner}/${repo}`;
const download = `${homepage}/releases/download/v${version}`;
const sha256 = (file) => createHash('sha256').update(readFileSync(file)).digest('hex');
const shaIfThere = (name) => (existsSync(join(releaseDir, name)) ? sha256(join(releaseDir, name)) : null);

const deb = `one-take_${version}_amd64.deb`;
const setup = `One-Take-Setup-${version}.exe`;
const debSha = shaIfThere(deb);
const setupSha = shaIfThere(setup);
if (!debSha && !setupSha) {
  console.error(`Neither ${deb} nor ${setup} is in ${releaseDir}`);
  process.exit(1);
}
const licenseSha = sha256(join(root, 'LICENSE'));
const description = pkg.description;
// Arch's guidelines leave the full stop off a package description.
const pkgdesc = description.replace(/\.$/, '').replace(/'/g, '');

function write(path, text) {
  mkdirSync(join(outDir, path, '..'), { recursive: true });
  writeFileSync(join(outDir, path), text);
  console.log(`Wrote ${join(outDir, path)}`);
}

if (debSha) {
// ---------- AUR: one-take-bin, repackaging the .deb ----------

const depends = ['alsa-lib', 'at-spi2-core', 'gtk3', 'libnotify', 'libsecret', 'libxss', 'libxtst', 'nss', 'util-linux-libs', 'xdg-utils'];
const list = (items) => items.map((d) => `'${d}'`).join(' ');

write('aur/PKGBUILD', `# Maintainer: Fixr <https://github.com/${owner}>
# Generated by scripts/package-manifests.mjs in ${homepage}

pkgname=one-take-bin
pkgver=${version}
pkgrel=1
pkgdesc='${pkgdesc}'
arch=('x86_64')
url='${homepage}'
license=('MIT')
depends=(${list(depends)})
provides=('one-take')
conflicts=('one-take')
options=('!strip' '!debug')
source=("${download.replace(version, '${pkgver}')}/one-take_\${pkgver}_amd64.deb"
        "LICENSE-\${pkgver}::https://raw.githubusercontent.com/${owner}/${repo}/v\${pkgver}/LICENSE")
noextract=("one-take_\${pkgver}_amd64.deb")
sha256sums=('${debSha}'
            '${licenseSha}')

package() {
  bsdtar -xOf "one-take_\${pkgver}_amd64.deb" 'data.tar.*' | bsdtar -xf - -C "\$pkgdir"
  rm -rf "\$pkgdir/usr/share/doc"
  # Electron's sandbox helper, set up as the .deb does on systems without user namespaces.
  chmod 4755 "\$pkgdir/opt/One Take/chrome-sandbox"
  install -dm755 "\$pkgdir/usr/bin"
  ln -s '/opt/One Take/one-take' "\$pkgdir/usr/bin/one-take"
  # Tells the app that updates come from the package manager.
  printf AUR > "\$pkgdir/opt/One Take/resources/package-manager"
  install -Dm644 "LICENSE-\${pkgver}" "\$pkgdir/usr/share/licenses/\$pkgname/LICENSE"
}
`);

write('aur/.SRCINFO', `pkgbase = one-take-bin
\tpkgdesc = ${pkgdesc}
\tpkgver = ${version}
\tpkgrel = 1
\turl = ${homepage}
\tarch = x86_64
\tlicense = MIT
${depends.map((d) => `\tdepends = ${d}`).join('\n')}
\tprovides = one-take
\tconflicts = one-take
\tnoextract = ${deb}
\toptions = !strip
\toptions = !debug
\tsource = ${download}/${deb}
\tsource = LICENSE-${version}::https://raw.githubusercontent.com/${owner}/${repo}/v${version}/LICENSE
\tsha256sums = ${debSha}
\tsha256sums = ${licenseSha}

pkgname = one-take-bin
`);
}

if (setupSha) {
// ---------- Scoop: the installer's files, unpacked without running it ----------

const scoopUrl = (v) => `${homepage}/releases/download/v${v}/One-Take-Setup-${v}.exe#/dl.7z`;
write('scoop/one-take.json', JSON.stringify({
  version,
  description,
  homepage,
  license: 'MIT',
  notes: 'Settings and sessions are kept in %APPDATA%\\One Take and Documents\\One Take, so they survive updates and uninstalling.',
  architecture: { '64bit': { url: scoopUrl(version), hash: setupSha } },
  installer: {
    script: [
      'Expand-7zipArchive "$dir\\`$PLUGINSDIR\\app-64.7z" "$dir"',
      'Remove-Item "$dir\\`$PLUGINSDIR", "$dir\\`$R0", "$dir\\uninstallerIcon.ico" -Recurse -Force -ErrorAction SilentlyContinue',
      'Set-Content "$dir\\resources\\package-manager" \'Scoop\' -NoNewline',
    ],
  },
  shortcuts: [['One Take.exe', 'One Take']],
  checkver: { github: homepage },
  autoupdate: { architecture: { '64bit': { url: scoopUrl('$version') } } },
}, null, 2) + '\n');

// ---------- winget: FeaXR.OneTake, the regular installer ----------

const id = `${owner}.OneTake`;
const schema = '1.10.0';
const header = (type) => `# yaml-language-server: $schema=https://aka.ms/winget-manifest.${type}.${schema}.schema.json\n# Generated by scripts/package-manifests.mjs in ${homepage}\n\n`;
const dir = `winget/manifests/${owner[0].toLowerCase()}/${owner}/OneTake/${version}`;

write(`${dir}/${id}.yaml`, `${header('version')}PackageIdentifier: ${id}
PackageVersion: ${version}
DefaultLocale: en-US
ManifestType: version
ManifestVersion: ${schema}
`);

// The installer updates itself, and winget sees that version in the list of installed programs.
write(`${dir}/${id}.installer.yaml`, `${header('installer')}PackageIdentifier: ${id}
PackageVersion: ${version}
InstallerType: nullsoft
Scope: user
UpgradeBehavior: install
ReleaseDate: ${new Date().toISOString().slice(0, 10)}
Installers:
- Architecture: x64
  InstallerUrl: ${download}/${setup}
  InstallerSha256: ${setupSha.toUpperCase()}
ManifestType: installer
ManifestVersion: ${schema}
`);

write(`${dir}/${id}.locale.en-US.yaml`, `${header('defaultLocale')}PackageIdentifier: ${id}
PackageVersion: ${version}
PackageLocale: en-US
Publisher: Fixr
PublisherUrl: https://github.com/${owner}
PublisherSupportUrl: ${homepage}/issues
PackageName: One Take
PackageUrl: ${homepage}
License: MIT
LicenseUrl: ${homepage}/blob/v${version}/LICENSE
ShortDescription: ${description}
Description: A focused editor for cutting one long WAV recording into several MP3 files, with consistent fades, cuts, and per-file loudness and bitrate. It can also record the WAV, and you can mark and export while the recording goes on.
Moniker: one-take
Tags:
- audio
- audio-editor
- mp3
- recording
- wav
ReleaseNotesUrl: ${homepage}/releases/tag/v${version}
ManifestType: defaultLocale
ManifestVersion: ${schema}
`);
}
